package com.log_to_kot.maniacmod.items;

/**
 * Імена анімацій предмета в його animation-файлі.
 *
 * ── Чому саме два ────────────────────────────────────────────────────
 *   {@code idle} — стан спокою в руці/на землі/в GUI. Це loop: він грає
 *                  весь час, поки предмет десь намальовано.
 *   {@code use}  — ОДНОРАЗОВА анімація використання (аптечка). Предмет,
 *                  який її не потребує (лом, каністра), просто не має
 *                  такої гілки в своєму animation-файлі — і ніколи її не
 *                  тригерить (див. {@link ItemArchetype#onUseClient}).
 *
 * ── Чому короткі імена ───────────────────────────────────────────────
 * GeckoLib сам додає префікс {@code animation.<id предмета>.} при пошуку
 * в animation-файлі, тож у файлі ключі мають бути
 * {@code animation.medkit.idle} і {@code animation.medkit.use}, а тут —
 * лише {@code idle}/{@code use}. Той самий підхід, що в
 * {@code ManiacAnimationSet}.
 *
 * ── Перевизначення ───────────────────────────────────────────────────
 * Художник, у якого інші імена, повертає свій сет із
 * {@link ItemVisuals} — але тоді кожне ім'я мусить існувати у файлі
 * анімацій, інакше GeckoLib тихо не програє цю гілку (предмет застигне в
 * позі попередньої анімації, помилки в лог може й не бути).
 */
public record ItemAnimationSet(String idle, String use) {

    /** Стандартні імена — те, що очікує код за замовчуванням. */
    public static ItemAnimationSet defaults() {
        return new ItemAnimationSet("idle", "use");
    }
}
