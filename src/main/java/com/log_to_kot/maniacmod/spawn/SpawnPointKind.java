package com.log_to_kot.maniacmod.spawn;

/**
 * Для чого призначена конкретна точка на карті.
 *
 * З ТЗ: маньяк спавниться НЕ там, де виживші — у кожного типу
 * маньяка своя стартова локація. Тому точки маньяка окремо
 * прив'язані до id архетипу (див. SpawnPoint.ownerId).
 */
public enum SpawnPointKind {

    /** Точка появи виживого. Одна точка = максимум ОДИН гравець. */
    SURVIVOR,

    /** Стартова локація конкретного маньяка (ownerId = id його архетипу, напр. "test_maniac"). */
    MANIAC,

    /** Точка, де МОЖЕ з'явитися предмет. Частина точок лишається порожньою. */
    ITEM,

    /** Точка, де стоїть сутність генератора. */
    GENERATOR,

    /**
     * Застарілий вид (v3: двері виходу). Нічого не спавнить — вихід замінила
     * евакуація вертольотом ({@code evac/}). Лишений, щоб старі {@code points.yml} читались.
     */
    EXIT,

    /**
     * Точка приймача. Розмічається багато, на матч обирається РІВНО одна.
     * Поворот сутності = куди дивився адмін у момент команди (yaw); нахил завжди 0.
     */
    RECEIVER,

    /**
     * Точка гака (механіка «підвісити виживого»). На відміну від RECEIVER, на матч
     * спавняться ВСІ розмічені гаки, а не один. Поворот сутності = куди дивився адмін у
     * момент команди (yaw); нахил завжди 0. Гаків може не бути взагалі — це не помилка плану.
     */
    HOOK,

    /**
     * Гачок сцени перемоги маніяка ({@code victory/}). Зовсім окрема від {@link #HOOK}: ті гачки —
     * ігрова механіка й живуть під час матчу, ці з'являються лише на кіно-сцені й несуть «опудала»
     * виживих. Розмічається 10+; поворот = куди дивився адмін, позиція точна.
     */
    VICTORY_HOOK,

    /** Місце маніяка у сцені перемоги. Поворот = куди дивився адмін, позиція точна (ступні). */
    VICTORY_MANIAC,

    /**
     * Дві точки камери сцени: перша — початок, друга — кінець руху. Позиція — точно ОЧІ адміна,
     * поворот — yaw/pitch погляду. Більше двох система не приймає.
     */
    VICTORY_CAMERA,

    /**
     * Місце ВИЖИВШОГО (того, хто втік) у сцені перемоги гравців: там стоїть модель гравця зі скіном
     * і танцює. Розмічається до 10 (максимум гравців у матчі); поворот = куди дивився адмін,
     * позиція точна (ступні).
     */
    VICTORY_PLAYER,

    /**
     * Місце ПРИВИДА у сцені перемоги гравців: тут висить у повітрі напівпрозорий блакитний «дух»
     * того, хто не вижив. Розмічається до 10; поворот = куди дивився адмін, позиція точна (ступні).
     */
    VICTORY_GHOST,

    /**
     * Необов'язкова пара камер сцени перемоги ГРАВЦІВ (початок і кінець руху, як
     * {@link #VICTORY_CAMERA}). Якщо не розмічена — сцена гравців їде по {@link #VICTORY_CAMERA}.
     */
    VICTORY_PLAYERS_CAMERA,

    /**
     * «Freecam»: ОДНА точка камери, з якої на екрані підсумків (статистика) видно світ за
     * інтерфейсом. Позиція — точно ОЧІ адміна, поворот — yaw/pitch погляду.
     */
    STATS_CAMERA
}
