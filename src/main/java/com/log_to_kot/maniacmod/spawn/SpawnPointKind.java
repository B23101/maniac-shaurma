package com.log_to_kot.maniacmod.spawn;

/**
 * Для чого призначена конкретна точка на карті.
 *
 * З ТЗ: маньяк спавниться НЕ там, де виживші — у кожного типу
 * маньяка своя стартова локація. Тому точки маньяка окремо
 * прив'язані до id архетипу (див. SpawnPoint.ownerId).
 */
public enum SpawnPointKind {

    /** Точка появи виживого. Одна точка = максимум ОДИН гравець. */
    SURVIVOR,

    /** Стартова локація конкретного маньяка (ownerId = id його архетипу, напр. "test_maniac"). */
    MANIAC,

    /** Точка, де МОЖЕ з'явитися предмет. Частина точок лишається порожньою. */
    ITEM,

    /** Точка, де стоїть сутність генератора. */
    GENERATOR,

    /** Точка виходу/воріт. */
    EXIT
}
