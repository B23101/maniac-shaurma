package com.log_to_kot.maniacmod.core.match;

/**
 * Лічильники особистої статистики гравця за матч. Показуються на екрані підсумків
 * ({@code MatchSummaryPacket}); джерело правди — {@code MatchStats} усередині {@code MatchContext}.
 *
 * <p>Нові значення — ЛИШЕ в кінець.</p>
 */
public enum MatchStat {
    /** Скільки разів гравець (маніяк) влучив по виживому. */
    HITS_DEALT,
    /** Скільки ударів маніяка отримав гравець (виживий). */
    HITS_TAKEN,
    /** Скільки разів гравець опинявся непритомним. */
    DOWNS,
    /** Скільки разів гравця повісили на гак. */
    HOOKS,
    /** Скількох товаришів гравець підняв. */
    RESCUES,
    /** Скільки ТІКІВ ремонту генераторів гравець вклав. */
    REPAIR_TICKS
}
