package com.log_to_kot.maniacmod.core.phase;

/**
 * Одна-єдина відповідь на питання "чи це справжня гра, чи технічна
 * вставка". Саме те, що в ТЗ названо "спільним списком: які фази
 * технічні, а які реально ігрові".
 *
 * TECHNICAL — кіно, розкидання, оголошення ролей, підсумки. Гравці
 *             можуть бути заморожені, урон вимкнений, HUD частковий.
 * GAMEPLAY  — фаза, у якій матч реально йде: полювання, живлення,
 *             фінал. Саме для цих фаз тікає ігрова логіка.
 *
 * Модуль, якому байдужі деталі, пише просто:
 *     if (!Phases.isGameplay()) return;
 * Модуль, якому потрібна конкретика, питає Phases.allows(PhaseRule.X).
 */
public enum PhaseKind {
    TECHNICAL,
    GAMEPLAY
}
