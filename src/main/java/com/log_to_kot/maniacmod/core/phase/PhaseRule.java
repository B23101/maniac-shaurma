package com.log_to_kot.maniacmod.core.phase;

/**
 * Дозволи (capabilities), які фаза видає модулям.
 *
 * НАВІЩО: щоб ніде в моді більше не було рядків типу
 *     if (ManiacGameManager.getGameState() != GameState.RUNNING) return;
 * Такий рядок у v3 дублювався у ServerEventHandler, ManiacGameManager,
 * GeneratorBlock, кожному предметі й кожному пакеті — і коли з'являється
 * нова фаза (кінематограф, розкидання, фінал), КОЖЕН із цих рядків стає
 * неправильним, бо "RUNNING" вже не відповідає на питання
 * "чи можна зараз бити гравця / ставити пастку / ремонтувати генератор".
 *
 * Замість цього модуль питає рівно те, що йому насправді треба:
 *     if (!Phases.allows(PhaseRule.DAMAGE)) return;
 *     if (!Phases.allows(PhaseRule.GENERATOR_REPAIR)) return;
 *
 * Додати нову фазу = дописати один рядок у GamePhase з набором дозволів.
 * Жоден існуючий модуль при цьому НЕ змінюється.
 */
public enum PhaseRule {

    /** Гравці можуть рухатись (у CINEMATIC/SCATTER — заморожені). */
    MOVEMENT,

    /** Маньяк може бити, виживші можуть отримувати урон. */
    DAMAGE,

    /** Маньяк може ставити пастки; пастки можуть спрацьовувати. */
    TRAPS,

    /** Генератори можна ремонтувати / заливати бензин. */
    GENERATOR_REPAIR,

    /** Предмети можна підбирати й використовувати. */
    ITEM_USE,

    /** Здібності маньяка активні (кулдауни тікають, активація дозволена). */
    ABILITIES,

    /** Виживші можуть відкривати вихід і тікати із зони втечі. */
    ESCAPE,

    /** Ігровий HUD (стаміна, підсвітка, прогрес генератора) показується. */
    HUD,

    /** Стаміна витрачається/відновлюється, серцебиття при маньяку поруч. */
    SURVIVOR_VITALS,

    /** Можна піднімати непритомних / воскрешати. */
    RESCUE
}
