package com.log_to_kot.maniacmod.evac;

/**
 * Внутрішній стан евакуації. Відрізняється від {@code GamePhase} навмисно: фаза — це
 * грубе «що дозволено» для решти модулів (HUD, голос, Tab), а стадія — дрібна механіка
 * самого вертольота, яку ніхто, крім {@code EvacModule}, знати не повинен.
 *
 * <pre>
 * DORMANT ─(виклик)→ WAIT_FLARE ─(ракета)→ DISPATCH ─→ INBOUND ─→ DESCEND ─→ ROPE_DROP
 *                                                                              │
 *            DONE ←─ DEPART ←─ ROPE_RETRACT ←─(час / нікого чекати)─ HOVER ←──┘
 * </pre>
 * Фаза: POWERED = DORMANT; HELI_WAIT = WAIT_FLARE…ROPE_DROP; FINALE = HOVER…DONE.
 * (Усі втекли — матч іде в ENDING раніше, але ROPE_RETRACT/DEPART допрацьовують і там.)
 */
enum EvacStage {
    /** Виклику ще не було. */
    DORMANT,
    /** Вертоліт викликано; чекаємо ракету на галявині. */
    WAIT_FLARE,
    /** Ракету запущено; вертоліт ще «збирається» (затримка). */
    DISPATCH,
    /** Летить із точки появи (далеко від галявини) по безпечному профілю висот до точки над нею. */
    INBOUND,
    /** Додатковий вертикальний спуск до висоти висіння (потрібен, лише якщо профіль закінчився вище). */
    DESCEND,
    /** Висить, мотузка розмотується. */
    ROPE_DROP,
    /** Мотузка готова, можна лізти. */
    HOVER,
    /** Відліт почався: мотузку підтягують угору. Хапатися вже не можна. */
    ROPE_RETRACT,
    /** Мотузка прибрана: вертоліт розвертається й відлітає тим самим безпечним шляхом. */
    DEPART,
    /** Усе скінчено. */
    DONE
}
