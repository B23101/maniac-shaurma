package com.log_to_kot.maniacmod.net;

import net.minecraft.network.FriendlyByteBuf;
import net.minecraftforge.network.NetworkEvent;

/**
 * Спільний контракт усіх пакетів мода.
 *
 * ── Що було не так у v3 ──────────────────────────────────────────────
 * Кожен пакет був самостійним класом без спільного типу, а реєстрація
 * в ModMessages вимагала шести рядків builder-ланцюжка на пакет із
 * ручним посиланням на три методи (decode/encode/handle). Помилитись
 * у порядку або переплутати NetworkDirection можна було мовчки —
 * компілятор нічого не перевіряв.
 *
 * Тепер: пакет реалізує цей інтерфейс, реєстрація — один рядок, а
 * напрямок (S2C/C2S) задається тим, який метод реєстрації викликано.
 *
 * Правила:
 *   - {@code encode} і конструктор-декодер мають читати/писати поля
 *     в ОДНОМУ порядку. Це єдине, за чим тут треба стежити вручну.
 *   - {@code handle} вже виконується в головному потоці (див.
 *     ModNetwork) — enqueueWork усередині не потрібен.
 *   - Пакет — незмінні дані. Жодної логіки в полях.
 */
public interface ModPacket {

    /** Записати поля в буфер. Порядок має збігатися з декодером. */
    void encode(FriendlyByteBuf buf);

    /**
     * Обробка. Викликається вже в головному потоці відповідної сторони.
     * Для C2S: {@code ctx.getSender()} — гравець-відправник, ніколи null.
     */
    void handle(NetworkEvent.Context ctx);
}
