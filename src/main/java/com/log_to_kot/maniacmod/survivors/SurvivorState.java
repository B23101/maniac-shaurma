package com.log_to_kot.maniacmod.survivors;

/**
 * Стан виживого — ОКРЕМО від ролі (SurvivorRole). Роль визначає
 * "хто" гравець (характеристики), стан визначає "що з ним зараз"
 * (здоровий/поламана нога/повзає/несвідомий). Один гравець за час
 * гри проходить кілька станів, лишаючись тією ж роллю.
 *
 * З презентації "Виживші":
 *   HEALTHY     — звичайний стан
 *   BROKEN_LEG  — стаміна скидається до нуля й не відновлюється,
 *                 лагодиться Шиною
 *   CRAWLING    — рух повзком (після поламаної ноги без Шини?
 *                 TODO уточнити точний тригер при перенесенні логіки)
 *   UNCONSCIOUS — 0 хп, гравець "у стані втрати свідомості", може
 *                 лише повзти, підсвічується на всю карту,
 *                 піднімається іншим гравцем (утримання ПКМ ~15с,
 *                 швидкість підняття залежить від кількості
 *                 гравців, що піднімають: x2/x3/x4 — не лінійно)
 *
 * v3-еквівалент: SurvivorData мав лише прапор `bound` (true/false) —
 * ця машина станів набагато детальніша і замінює його.
 */
public enum SurvivorState {

    HEALTHY,
    BROKEN_LEG,
    CRAWLING,
    UNCONSCIOUS;

    /** Чи може гравець у цьому стані бігати/стрибати нормально. */
    public boolean canSprint() {
        return this == HEALTHY;
    }

    /** Чи гравець зараз обмежений лише повзанням. */
    public boolean isCrawlOnly() {
        return this == CRAWLING || this == UNCONSCIOUS;
    }

    /** Чи потребує допомоги іншого гравця, щоб вийти з цього стану. */
    public boolean requiresRescue() {
        return this == UNCONSCIOUS;
    }
}
