package com.log_to_kot.maniacmod.survivors;

import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.phys.Vec3;

/**
 * МІСЦЕ ПІД АНІМАЦІЮ СМЕРТІ виживого.
 *
 * Зараз анімації немає, тож {@link #play} одразу викликає {@code onFinished}.
 * Але весь код смерті вже написаний так, ніби вона є: {@code SurvivorModule}
 * НЕ переводить гравця в глядачі й НЕ розкидає предмети сам, а віддає це
 * сюди колбеком. Коли анімація з'явиться, змінюється лише цей клас.
 *
 * ── Що вміє шов ──────────────────────────────────────────────────────
 * Може затримати завершення: показати анімацію (частинки, звук, поза
 * тіла, камера-розворот), і викликати {@code onFinished} по її кінці.
 * Поки він не викликаний, гравець лишається в матчі як мертвий-але-ще-тут:
 * {@code SurvivorModule} ставить йому мітку «помирає», щоб повторний удар
 * маньяка чи повторне спрацювання таймера не запустили смерть удруге.
 *
 * ── Контракт ─────────────────────────────────────────────────────────
 *   • {@code onFinished} викликається РІВНО ОДИН раз (або жодного, якщо
 *     гравець вийшов із сервера й матч це помітив — сервер сам приб'є
 *     мітку «помирає»);
 *   • викликати його треба на серверному потоці (з тіку чи події);
 *   • {@code position} — де лежало тіло, з розрахунку, що гравця вже може
 *     й не бути онлайн, коли анімація закінчиться.
 */
public final class SurvivorDeathSequence {

    /**
     * Запускає анімацію смерті й по її завершенні викликає {@code onFinished}.
     * Поточна реалізація — без анімації.
     */
    public void play(ServerPlayer player, Vec3 position, Runnable onFinished) {
        // TODO(death-animation): показати анімацію в position і викликати
        // onFinished по її завершенні (таймер у тіках через MatchScheduler).
        onFinished.run();
    }
}
